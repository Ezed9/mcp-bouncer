# bouncer/benchmark/make_address_book_policy.py
"""Write the address-book policy variant for the AgentDojo run: the default
workspace pack plus `trusted_destinations` = every address in the workspace
contact list, on each send tool. Offline: reads AgentDojo's bundled data only.

AgentDojo builds that contact list from every sender and recipient in the
inbox, so it includes the senders of the suite's own phishing emails. It does
not include the attacker address used by the injection tasks.

Run: uv run --extra benchmark python -m benchmark.make_address_book_policy
Then: ... python -m benchmark.run_agentdojo --policy <printed path> ...
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import yaml

from benchmark.run_agentdojo import (
    _ATTACKER,
    _DEFAULT_SUITE_VERSION,
    _WORKSPACE_PACK,
    _default_env,
    _load_suite,
)

_OUT = Path(__file__).with_name("agentdojo_workspace_address_book.yaml")


def _contacts(suite_version: str) -> list[str]:
    env = _default_env(_load_suite(suite_version))
    return sorted({c.email for c in env.inbox.contact_list})


def build_policy(default_policy: dict[str, dict], contacts: list[str]) -> dict[str, dict]:
    policy = {tool: dict(entry) for tool, entry in default_policy.items()}
    for entry in policy.values():
        if entry.get("exfiltrating"):
            entry["trusted_destinations"] = sorted(
                {*entry.get("trusted_destinations", []), *contacts})
    return policy


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--suite-version", default=_DEFAULT_SUITE_VERSION)
    parser.add_argument("--out", type=Path, default=_OUT)
    args = parser.parse_args()

    contacts = _contacts(args.suite_version)
    if _ATTACKER in contacts:
        raise ValueError(f"the contact list contains the attacker {_ATTACKER}; "
                         "the variant would trust the exfiltration target")
    policy = build_policy(yaml.safe_load(_WORKSPACE_PACK.read_text()), contacts)
    header = (
        f"# GENERATED by benchmark/make_address_book_policy.py from {_WORKSPACE_PACK.name}\n"
        f"# plus the AgentDojo workspace {args.suite_version} contact list "
        f"({len(contacts)} addresses) as trusted_destinations.\n"
        "# Do not edit by hand; regenerate and record the sha256.\n"
    )
    text = header + yaml.safe_dump(policy, sort_keys=False)
    args.out.write_text(text)
    print(f"wrote {args.out} ({len(contacts)} trusted addresses)")
    print(f"sha256 {hashlib.sha256(text.encode()).hexdigest()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
